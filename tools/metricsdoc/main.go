// Command metricsdoc writes the metrics reference of the user documentation
// from the metrics Relic registers (telemetry.Catalog).
package main

import (
	"fmt"
	"os"
	"strings"

	"relic/internal/platform/telemetry"
)

const page = "web/layers/site/content/docs/3.guides/6.metrics-reference.md"

func main() {
	if err := os.WriteFile(page, []byte(render()), 0o644); err != nil { //nolint:gosec // a public documentation page
		fmt.Fprintln(os.Stderr, "metricsdoc:", err)
		os.Exit(1)
	}
}

func render() string {
	var b strings.Builder
	b.WriteString(`---
title: Metrics reference
description: Every series Relic exports on its metrics port, with its labels.
---

<!-- Generated by go run ./tools/metricsdoc from the registered metrics. Do not edit. -->

Relic serves these series at ` + "`/metrics`" + ` on its metrics port
(` + "`RELIC_METRICS_LISTEN_ADDRESS`" + `, default ` + "`:8091`" + `), besides the Go runtime (` + "`go_*`" + `) and
process (` + "`process_*`" + `) collectors. Label values are bounded: routes are the
router's patterns, formats and classes come from fixed lists, and anything
unknown is ` + "`other`" + `. A ` + "`repository`" + ` label marked (opt-in) appears only with
` + "`RELIC_METRICS_REPOSITORY_LABEL=true`" + `; the replication gauges carry it always,
one series per configured replication. Histograms also export ` + "`_bucket`" + `,
` + "`_sum`" + ` and ` + "`_count`" + `, and latency histograms carry the trace ID as an exemplar.
See [Monitoring](/docs/guides/monitoring) for the dashboards and alerts.

| Series | Type | Labels | Meaning |
| --- | --- | --- | --- |
`)

	for _, m := range telemetry.Catalog() {
		labels := make([]string, 0, len(m.Labels)+1)
		for _, l := range m.Labels {
			labels = append(labels, "`"+l+"`")
		}

		if m.RepositoryLabel {
			labels = append(labels, "`repository` (opt-in)")
		}

		fmt.Fprintf(
			&b,
			"| `%s` | %s | %s | %s |\n",
			m.Name,
			m.Type,
			strings.Join(labels, ", "),
			strings.ReplaceAll(m.Help, "|", "\\|"),
		)
	}

	return b.String()
}
