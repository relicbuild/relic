package scan

import (
	"path/filepath"
	"strings"
	"testing"
)

const smallvecCargoToml = `# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO

[package]
edition = "2018"
name = "smallvec"
version = "1.6.0"
authors = ["The Servo Project Developers"]
description = "'Small vector' optimization: store up to a small number of items on the stack"

[dependencies.serde]
version = "1"
optional = true
`

const newtonsoftNuspec = `<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://schemas.microsoft.com/packaging/2012/06/nuspec.xsd">
  <metadata minClientVersion="2.12">
    <id>Newtonsoft.Json</id>
    <version>12.0.1</version>
    <authors>James Newton-King</authors>
  </metadata>
</package>
`

func TestWithArchivePackage(t *testing.T) {
	t.Parallel()

	tests := map[string]struct {
		file     string
		contents map[string]string
		sbom     string
		want     string
		count    int
	}{
		"a crate adds its own package": {
			file: "smallvec-1.6.0.crate",
			contents: map[string]string{
				"smallvec-1.6.0/Cargo.toml":      smallvecCargoToml,
				"smallvec-1.6.0/Cargo.toml.orig": "[package]\nname = \"other\"\nversion = \"9.9.9\"\n",
				"smallvec-1.6.0/lib.rs":          "pub struct SmallVec;",
			},
			sbom:  `{"artifacts":[],"schema":{"version":"16.1.10"}}`,
			want:  "pkg:cargo/smallvec@1.6.0",
			count: 1,
		},
		"a NuGet package adds its own package": {
			file: "newtonsoft.json.12.0.1.nupkg",
			contents: map[string]string{
				"Newtonsoft.Json.nuspec":                   newtonsoftNuspec,
				"lib/netstandard2.0/Newtonsoft.Json.dll":   "dll",
				"[Content_Types].xml":                      "<Types/>",
				"package/services/metadata/core-props.txt": "props",
			},
			sbom: `{"artifacts":[{"id":"a","name":"Json.NET","version":"12.0.1.22727","type":"dotnet",` +
				`"purl":"pkg:nuget/Json.NET@12.0.1.22727"}]}`,
			want:  "pkg:nuget/Newtonsoft.Json@12.0.1",
			count: 2,
		},
		"a package Syft already found is not added twice": {
			file: "smallvec-1.6.0.crate",
			contents: map[string]string{
				"smallvec-1.6.0/Cargo.toml": smallvecCargoToml,
			},
			sbom:  `{"artifacts":[{"id":"a","name":"smallvec","version":"1.6.0","purl":"pkg:cargo/smallvec@1.6.0"}]}`,
			want:  "pkg:cargo/smallvec@1.6.0",
			count: 1,
		},
		"another archive is left as Syft cataloged it": {
			file: "lodash-4.17.15.tgz",
			contents: map[string]string{
				"package/package.json": `{"name":"lodash","version":"4.17.15"}`,
			},
			sbom:  `{"artifacts":[]}`,
			count: 0,
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			archive := filepath.Join(dir, tt.file)

			if strings.HasSuffix(tt.file, ".nupkg") {
				writeZip(t, archive, tt.contents)
			} else {
				writeTarGz(t, archive, tt.contents)
			}

			s := NewService(nil, nil, nil, nil, Limits{}, nil)

			source, _, err := s.prepare(archive, filepath.Join(dir, "src"))
			if err != nil {
				t.Fatal(err)
			}

			got := withArchivePackage([]byte(tt.sbom), tt.file, source)

			components, err := syftComponents(got)
			if err != nil {
				t.Fatalf("the SBOM no longer reads: %v\n%s", err, got)
			}

			if len(components) != tt.count {
				t.Errorf("components = %+v, want %d", components, tt.count)
			}

			if tt.want != "" && !strings.Contains(string(got), `"purl":"`+tt.want+`"`) {
				t.Errorf("SBOM %s, want the package %s", got, tt.want)
			}
		})
	}
}

func TestWithArchivePackageKeepsOtherFormats(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	archive := filepath.Join(dir, "smallvec-1.6.0.crate")
	writeTarGz(t, archive, map[string]string{
		"smallvec-1.6.0/Cargo.toml": smallvecCargoToml,
	})

	s := NewService(nil, nil, nil, nil, Limits{}, nil)

	source, _, err := s.prepare(archive, filepath.Join(dir, "src"))
	if err != nil {
		t.Fatal(err)
	}

	sbom := `{"bomFormat":"CycloneDX","components":[]}`
	if got := withArchivePackage([]byte(sbom), "smallvec-1.6.0.crate", source); string(got) != sbom {
		t.Errorf("a CycloneDX document became %s", got)
	}
}

func TestCargoPackage(t *testing.T) {
	t.Parallel()

	tests := map[string]struct {
		manifest string
		name     string
		version  string
	}{
		"normalized": {
			manifest: smallvecCargoToml,
			name:     "smallvec",
			version:  "1.6.0",
		},
		"literal strings and comments": {
			manifest: "[package]\nname = 'serde' # the crate\nversion = '1.0.0'\n",
			name:     "serde",
			version:  "1.0.0",
		},
		"keys outside the package table": {
			manifest: "[dependencies.x]\nname = \"x\"\nversion = \"1\"\n[package]\nname = \"y\"\n",
			name:     "y",
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			gotName, gotVersion := cargoPackage([]byte(tt.manifest))
			if gotName != tt.name || gotVersion != tt.version {
				t.Errorf("cargoPackage = %q %q, want %q %q", gotName, gotVersion, tt.name, tt.version)
			}
		})
	}
}
