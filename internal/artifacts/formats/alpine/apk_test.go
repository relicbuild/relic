func apkOf(t *testing.T, pkginfo string) (apk, control []byte) {
	t.Helper()

	now := time.Unix(1_700_000_000, 0)

	sig, err := gzipTar([]tarFile{
		{
			".SIGN.RSA.builder.rsa.pub",
			[]byte("sig"),
		},
	}, now, false)
	if err != nil {
		t.Fatal(err)
	}

	control, err = gzipTar([]tarFile{
		{
			".PKGINFO",
			[]byte(pkginfo),
		},
	}, now, false)
	if err != nil {
		t.Fatal(err)
	}

	data, err := gzipTar([]tarFile{
		{
			"usr/bin/hello",
			[]byte("#!/bin/sh\necho hello\n"),
		},
	}, now, true)
	if err != nil {
		t.Fatal(err)
	}

	return append(append(append([]byte{}, sig...), control...), data...), control
}

const pkginfo = "# Generated by abuild\npkgname = hello\npkgver = 1.0-r0\npkgdesc = Says hello\nurl = https://example.org\n" +
	"builddate = 1700000000\nsize = 4096\narch = x86_64\nlicense = MIT\norigin = hello\ndepend = musl\ndepend = so:libc.musl-x86_64.so.1\nprovides = cmd:hello=1.0-r0\n"

func TestParse(t *testing.T) {
	t.Parallel()
	apk, control := apkOf(t, pkginfo)

	got, err := Parse(bytes.NewReader(apk))
	if err != nil {
		t.Fatal(err)
	}

	sum := sha1.Sum(control) //nolint:gosec // apk format
	if want := "Q1" + base64.StdEncoding.EncodeToString(sum[:]); got.Checksum != want {
		t.Errorf("checksum = %s, want %s (SHA-1 of the control member)", got.Checksum, want)
	}

	if got.Name != "hello" || got.Version != "1.0-r0" || got.Arch != "x86_64" || got.Size != int64(len(apk)) ||
		got.Installed != 4096 {
		t.Errorf("package = %+v", got)
	}

	stanza := got.Stanza()
	for _, want := range []string{
		"P:hello\n",
		"V:1.0-r0\n",
		"D:musl so:libc.musl-x86_64.so.1\n",
		"p:cmd:hello=1.0-r0\n",
		"L:MIT\n",
	} {
		if !strings.Contains(stanza, want) {
			t.Errorf("stanza lacks %q:\n%s", want, stanza)
		}
	}

	if _, err := Parse(strings.NewReader("not gzip")); !errors.Is(err, ErrInvalid) {
		t.Errorf("garbage = %v", err)
	}

	padding := maxMember/maxControl + 1
	dotFiles := make([]tarFile, 0, 1+padding)

	dotFiles = append(
		dotFiles,
		tarFile{
			".PKGINFO",
			[]byte(pkginfo),
		},
	)
	for i := range padding {
		dotFiles = append(
			dotFiles,
			tarFile{
				fmt.Sprintf(".pad%d", i),
				bytes.Repeat([]byte("x"), maxControl),
			},
		)
	}

	padded, err := gzipTar(dotFiles, time.Unix(1_700_000_000, 0), false)
	if err != nil {
		t.Fatal(err)
	}

	if _, err := Parse(bytes.NewReader(padded)); !errors.Is(err, ErrInvalid) {
		t.Errorf("control files above the member cap = %v", err)
	}
}

func TestIndex(t *testing.T) {
	t.Parallel()

	signers := make([]Signer, 0, 2)

	for _, name := range []string{
		"relic-rsa",
		"relic-rsa-next",
	} {
		key, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			t.Fatal(err)
		}

		signers = append(signers, Signer{
			Key:  key,
			Name: name,
		})
	}

	stanzas := []string{
		"C:Q1abc=\nP:a\nV:1\n",
		"C:Q1def=\nP:b\nV:2\n",
	}

	idx, err := Index(stanzas, "relic", signers, time.Now())
	if err != nil {
		t.Fatal(err)
	}

	got, err := Stanzas(bytes.NewReader(idx))
	if err != nil || len(got) != 2 || got[1] != stanzas[1] {
		t.Fatalf("Stanzas = %q %v", got, err)
	}

	zr, err := gzip.NewReader(bytes.NewReader(idx))
	if err != nil {
		t.Fatal(err)
	}

	zr.Multistream(false)

	signatures := map[string][]byte{}
	tr := tar.NewReader(zr)

	for {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}

		if err != nil {
			t.Fatal(err)
		}

		body, err := io.ReadAll(tr)
		if err != nil {
			t.Fatal(err)
		}

		signatures[h.Name] = body
	}

	sum := sha1.Sum(idx[firstMemberLen(t, idx):]) //nolint:gosec // apk format

	for _, signer := range signers {
		sig, ok := signatures[".SIGN.RSA."+signer.Name+".rsa.pub"]
		if !ok {
			t.Errorf("no signature entry named after %s: %v", signer.Name, slices.Collect(maps.Keys(signatures)))
			continue
		}

		if err := rsa.VerifyPKCS1v15(&signer.Key.PublicKey, crypto.SHA1, sum[:], sig); err != nil {
			t.Errorf("the signature of %s does not verify: %v", signer.Name, err)
		}
	}
}

func firstMemberLen(t *testing.T, b []byte) int {
	t.Helper()

	r := bytes.NewReader(b)

	zr, err := gzip.NewReader(r)
	if err != nil {
		t.Fatal(err)
	}

	zr.Multistream(false)

	if _, err := new(bytes.Buffer).ReadFrom(zr); err != nil {
		t.Fatal(err)
	}

	return len(b) - r.Len()
}
