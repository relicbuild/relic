// Command inventory generates compat/docs/commands.yaml from a pinned client
// binary and renders compat/docs/MATRIX.md from it.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"os/signal"
	"strings"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	defer stop()

	if err := run(ctx, os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "inventory:", err)
		stop()
		os.Exit(1)
	}
}

func run(ctx context.Context, args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: inventory generate|matrix [flags]")
	}

	fset := flag.NewFlagSet(args[0], flag.ContinueOnError)
	inventoryPath := fset.String(
		"inventory",
		"api/adapters/artifactory/compat/docs/commands.yaml",
		"commands.yaml path",
	)

	switch args[0] {
	case "generate":
		jf := fset.String("cli", "jf", "path to the pinned jf binary")

		rulesPath := fset.String("rules", "api/adapters/artifactory/compat/inventory/tiers.yaml", "tier rules")
		if err := fset.Parse(args[1:]); err != nil {
			return err
		}

		return generate(ctx, *jf, *rulesPath, *inventoryPath)
	case "matrix":
		out := fset.String("out", "api/adapters/artifactory/compat/docs/MATRIX.md", "output path")
		required := fset.String(
			"required",
			"api/adapters/artifactory/compat/e2e/required.txt",
			"required e2e scenarios",
		)

		scenarios := fset.String("scenarios", "api/adapters/artifactory/compat/fixtures/scenarios", "scenario scripts")
		if err := fset.Parse(args[1:]); err != nil {
			return err
		}

		inv, err := readInventory(*inventoryPath)
		if err != nil {
			return err
		}

		covered, err := coveredCommands(*required, *scenarios)
		if err != nil {
			return err
		}

		f, err := os.Create(*out)
		if err != nil {
			return err
		}

		if err := writeMatrix(f, inv, covered); err != nil {
			_ = f.Close()
			return err
		}

		return f.Close()
	default:
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func generate(ctx context.Context, jf, rulesPath, inventoryPath string) error {
	var rules Rules
	if err := readYAML(rulesPath, &rules); err != nil {
		return err
	}

	home, err := os.MkdirTemp("", "inventory-jf-home-")
	if err != nil {
		return err
	}

	defer func() {
		_ = os.RemoveAll(home)
	}()

	runJF := func(ctx context.Context, args ...string) (string, error) {
		cmd := exec.CommandContext(ctx, jf, args...)
		// Hermetic: an empty PATH so a wrapped tool (npm, docker, ...) can never run.
		cmd.Env = []string{
			"HOME=" + home,
			"JFROG_CLI_HOME_DIR=" + home,
			"PATH=" + home,
			"JFROG_CLI_AI_HELP=false",
			"JFROG_CLI_REPORT_USAGE=false",
			"CI=true",
		}

		var stdout bytes.Buffer

		cmd.Stdout = &stdout
		err := cmd.Run()

		return stdout.String(), err
	}
	help := func(ctx context.Context, args ...string) string {
		out, _ := runJF(ctx, args...)
		return out
	}

	version, err := runJF(ctx, "--version")
	if err != nil {
		return fmt.Errorf("jf --version: %w", err)
	}

	fish, err := runJF(ctx, "completion", "fish")
	if err != nil {
		return fmt.Errorf("jf completion fish: %w", err)
	}

	visible := walk(ctx, help, fishParents(fish))
	if diffs := crossCheck(visible, fishNameGroups(fish)); len(diffs) > 0 {
		return fmt.Errorf("--help tree and fish completion disagree:\n  %s", strings.Join(diffs, "\n  "))
	}

	hidden := probeHidden(ctx, help, rules.HiddenCandidates, visible)
	if err := ctx.Err(); err != nil {
		return fmt.Errorf("interrupted while reading jf's commands: %w", err)
	}

	inv := Inventory{
		JFVersion: strings.TrimPrefix(strings.TrimSpace(version), "jf version "),
	}

	for _, d := range append(visible, hidden...) {
		c := Command{
			Command: d.Path,
			Aliases: d.Aliases,
			Hidden:  d.Hidden,
			Flags:   d.Flags,
		}

		classify(&c, rules.Rules)
		inv.Commands = append(inv.Commands, c)
	}

	header := "# Generated by `go run ./api/adapters/artifactory/compat/inventory generate`. Edit api/adapters/artifactory/compat/inventory/tiers.yaml, not tiers here.\n"

	fmt.Fprintf(
		os.Stderr,
		"inventory: jf %s: %d visible + %d hidden commands\n",
		inv.JFVersion,
		len(visible),
		len(hidden),
	)

	return writeYAML(inventoryPath, header, inv)
}
